-- Business tables for the dedicated ACL database. User owns the identities
-- referenced by share metadata. Authorization resolves groups through User.
CREATE TABLE acl_service.acl_casbin_rules (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES acl_service.service_tenants (tenant_id),
    ptype varchar(255),
    v0 varchar(255), v1 varchar(255), v2 varchar(255),
    v3 varchar(255), v4 varchar(255), v5 varchar(255),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_acl_casbin_rules_tenant ON acl_service.acl_casbin_rules (tenant_id);

CREATE TABLE acl_service.sociacl_share_links (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES acl_service.service_tenants (tenant_id),
    token_hash varchar(64) NOT NULL UNIQUE,
    token_prefix varchar(16) NOT NULL,
    owner_user_id uuid,
    group_id uuid,
    resource_kind varchar(32) NOT NULL,
    resource_descriptor jsonb NOT NULL DEFAULT '{}'::jsonb,
    predicate_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    mode varchar(32) NOT NULL,
    expires_at timestamptz,
    uses_remaining integer,
    revoked_at timestamptz,
    created_by varchar(512),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_sociacl_share_links_tenant ON acl_service.sociacl_share_links (tenant_id);

CREATE TABLE acl_service.sociacl_recovery_sessions (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES acl_service.service_tenants (tenant_id),
    state varchar(32) NOT NULL,
    idempotency_key varchar(128) NOT NULL,
    expires_at timestamptz NOT NULL,
    metadata jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_sociacl_recovery_sessions_tenant ON acl_service.sociacl_recovery_sessions (tenant_id);

CREATE TABLE acl_service.sociacl_witness_policy (
    id integer PRIMARY KEY,
    revision bigint NOT NULL DEFAULT 0,
    jwks jsonb NOT NULL DEFAULT '{"keys":[]}'::jsonb,
    history jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_sociacl_policy_singleton CHECK (id = 1),
    CONSTRAINT ck_sociacl_policy_revision CHECK (revision BETWEEN 0 AND 9007199254740991)
);
CREATE TABLE acl_service.sociacl_keyring_state (
    principal varchar(87) PRIMARY KEY,
    head_floor bigint NOT NULL DEFAULT 0,
    recovery_generation bigint NOT NULL DEFAULT 0,
    wrap_generation bigint NOT NULL DEFAULT 0,
    recovery bytea NOT NULL DEFAULT ''::bytea,
    wraps bytea NOT NULL DEFAULT ''::bytea,
    CONSTRAINT ck_sociacl_keyring_principal CHECK (principal ~ '^[A-Za-z0-9_-]{43}[.][A-Za-z0-9_-]{43}$'),
    CONSTRAINT ck_sociacl_keyring_floor CHECK (head_floor BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_sociacl_recovery_generation CHECK (recovery_generation BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_sociacl_wrap_generation CHECK (wrap_generation BETWEEN 0 AND 9007199254740991)
);
CREATE TABLE acl_service.sociacl_checkpoint_requests (
    request_hash varchar(64) PRIMARY KEY,
    consumed_at bigint NOT NULL,
    CONSTRAINT ck_checkpoint_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_checkpoint_consumed_at CHECK (consumed_at BETWEEN 0 AND 9007199254740991)
);

