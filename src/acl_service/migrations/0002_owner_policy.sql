-- Only the migration owner bypasses RLS on this table. The runtime can resolve
-- an exact capability hash through this function and receives only row IDs.
CREATE FUNCTION acl_service.sociacl_share_lookup_by_hash(p_hash varchar)
RETURNS TABLE (id uuid, tenant_id uuid)
LANGUAGE sql STABLE STRICT SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $function$
    SELECT link.id, link.tenant_id
    FROM acl_service.sociacl_share_links AS link
    WHERE link.token_hash OPERATOR(pg_catalog.=) p_hash
$function$;
REVOKE ALL ON FUNCTION acl_service.sociacl_share_lookup_by_hash(varchar) FROM PUBLIC;
